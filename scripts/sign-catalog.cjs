'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { validateCatalog } = require('../desktop/core/catalog.cjs');
const root = path.resolve(__dirname, '..');
const keyPath = process.env.MEDIAHUB_SIGNING_KEY || path.join(root, '.publisher/catalog-private.pem');
const [input, output] = process.argv.slice(2);
if (!input || !output) throw new Error('Usage: node scripts/sign-catalog.cjs CATALOG.json SIGNED.json');
const catalog = validateCatalog(JSON.parse(fs.readFileSync(input, 'utf8').replace(/^\uFEFF/, '')));
if (!Number.isSafeInteger(catalog.sequence)) throw new Error('Catalog requires monotonic integer sequence');
const bytes = Buffer.from(JSON.stringify(catalog));
const privateKey = crypto.createPrivateKey(fs.readFileSync(keyPath));
const publicKey = crypto.createPublicKey(privateKey);
const keyId = crypto.createHash('sha256').update(publicKey.export({ type: 'spki', format: 'der' })).digest('hex').slice(0, 16);
const signature = crypto.sign(null, bytes, privateKey).toString('base64');
fs.mkdirSync(path.dirname(path.resolve(output)), { recursive: true });
fs.writeFileSync(output, JSON.stringify({ algorithm: 'Ed25519', keyId, payload: bytes.toString('base64'), signature }, null, 2));
console.log(JSON.stringify({ output, keyId, sequence: catalog.sequence }));
